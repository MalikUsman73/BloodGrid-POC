import { writeFileSync } from 'node:fs';
import { SECTORS } from '../src/data/sectors';
import { generateDonors } from '../src/data/synthetic';

const sectorValues = SECTORS.map((s) => `  ('${s.id}', ${s.lat}, ${s.lng})`).join(',\n');
const donorValues = generateDonors()
  .map(
    (d) =>
      `('${d.code}','${d.group}','${d.sector}',${d.daysSinceDonation},${d.available ? 1 : 0},${d.accepted},${d.received},${d.contactsLast30d})`,
  )
  .join(',\n');

const sql = `-- Synthetic data only. Generated by scripts/generate-seed.ts (seeded, reproducible).
insert into public.sectors (id, lat, lng) values
${sectorValues}
on conflict (id) do nothing;

insert into public.donors
  (code, blood_group, sector_id, last_donation_date, available, accepted_count, received_count, contacts_last_30d,
   base_accepted, base_received, base_contacts)
select code, grp, sec, current_date - days, av = 1, acc, rec, con, acc, rec, con
from (values
${donorValues}
) as v(code, grp, sec, days, av, acc, rec, con)
on conflict (code) do nothing;
`;

writeFileSync('supabase/seed.sql', sql);
console.log('Wrote supabase/seed.sql');
